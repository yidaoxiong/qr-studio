const LANGS = [
  { id: 'zh', label: '中文' },
  { id: 'en', label: 'English' },
  { id: 'es', label: 'Español' },
];
const HTML_LANG = { zh: 'zh-CN', en: 'en', es: 'es' };

/* 语言 persisted在 localStorage；file:// 下 localStorage 可能不可用，全部包 try */
let LANG = 'zh';
try {
  const saved = localStorage.getItem('qr.lang');
  if (saved && I18N[saved]) LANG = saved;
} catch (e) {}

function setLang(id) {
  if (!I18N[id]) return;
  LANG = id;
  try { localStorage.setItem('qr.lang', id); } catch (e) {}
}

/** 取文案；支持 {param} 占位替换 */
function t(key, params) {
  const dict = I18N[LANG] || I18N.zh;
  let s = dict[key];
  if (s === undefined) s = (I18N.zh[key] !== undefined ? I18N.zh[key] : key);
  if (params) {
    for (const k in params) s = s.split('{' + k + '}').join(params[k]);
  }
  return s;
}

/** 把 [data-i18n] / [data-i18n-html] / [data-i18n-ph] / [data-i18n-title] 填进去 */
function applyStaticText() {
  document.documentElement.lang = HTML_LANG[LANG] || 'en';
  document.title = t('docTitle');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  // 文案里带 <b> 等标记的用这个（只有我们自己的字典会进来，不是用户输入）
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}
